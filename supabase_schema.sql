-- 1. Buat Tabel Events (Daftar Lomba & Hackathon)
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    organizer TEXT,
    category TEXT,
    level TEXT,
    fee TEXT,
    prize TEXT,
    deadline TEXT,
    location TEXT,
    contact TEXT,
    status TEXT DEFAULT 'Pendaftaran Buka',
    reg_link TEXT,
    image_url TEXT,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Buat Tabel Teams (Postingan Cari Teman Satu Tim)
CREATE TABLE IF NOT EXISTS public.teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT REFERENCES public.events(id) ON DELETE SET NULL,
    event_title TEXT,
    name TEXT NOT NULL,
    my_role TEXT,
    needed_role TEXT,
    contact TEXT,
    message TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Aktifkan Row Level Security (RLS)
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.teams ENABLE ROW LEVEL SECURITY;

-- 4. Kebijakan Akses (Policies) agar API Express/Client dapat membaca dan menyimpan data
DROP POLICY IF EXISTS "Public read events" ON public.events;
CREATE POLICY "Public read events" ON public.events FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public insert events" ON public.events;
CREATE POLICY "Public insert events" ON public.events FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Public update events" ON public.events;
CREATE POLICY "Public update events" ON public.events FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Public delete events" ON public.events;
CREATE POLICY "Public delete events" ON public.events FOR DELETE USING (true);

DROP POLICY IF EXISTS "Public read teams" ON public.teams;
CREATE POLICY "Public read teams" ON public.teams FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public insert teams" ON public.teams;
CREATE POLICY "Public insert teams" ON public.teams FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Public delete teams" ON public.teams;
CREATE POLICY "Public delete teams" ON public.teams FOR DELETE USING (true);

